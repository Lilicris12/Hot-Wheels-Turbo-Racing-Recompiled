// which SDL's platform entry point (Java activity / UIApplicationMain) calls.
#if !defined(__ANDROID__) && !(defined(__APPLE__) && TARGET_OS_IPHONE)
#   define SDL_MAIN_HANDLED
#endif
#include "SDL.h"
#include "SDL_main.h"
#include "SDL_syswm.h"
#if defined(__APPLE__)
#   include "SDL_metal.h"
#endif
#if defined(__linux__)
// SDL_syswm.h pulls in X11, whose macros collide with RT64/ultramodern identifiers.
#   undef None
#   undef Status
#   undef LockMask
#   undef ControlMask
#   undef Success
#   undef Always
#endif

